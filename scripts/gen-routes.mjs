// Generates thin page wrappers for English (app/(en)/...) and Hindi (app/hi/...).
// Run: node scripts/gen-routes.mjs
import fs from 'node:fs';
import path from 'node:path';

const routes = [
  { path: '', view: 'home', title: null },
  { path: 'help', view: 'help', title: 'nav.help' },
  { path: 'plan', view: 'plan', title: 'plan.title' },
  { path: 'under-18', view: 'under18', title: 'u18.title' },
  { path: 'platforms', view: 'platforms', title: 'platforms.title' },
  { path: 'platforms/[id]', kind: 'platform' },
  { path: 'draft', view: 'draft', title: 'draft.title' },
  { path: 'evidence', view: 'evidence', title: 'evidence.title' },
  { path: 'case', view: 'case', title: 'case.title' },
  { path: 'tracker', view: 'tracker', title: 'tracker.title' },
  { path: 'tracker/[id]', kind: 'tracker' },
  { path: 'tracker/compare', view: 'tracker', named: 'TrackerCompare', title: 'tracker.compare' },
  { path: 'tracker/methodology', view: 'tracker', named: 'TrackerMethodology', title: 'tracker.methodology' },
  { path: 'tracker/incidents', view: 'tracker', named: 'TrackerIncidents', title: 'tracker.incidents' },
  { path: 'learn', kind: 'learn' },
  { path: 'learn/[slug]', kind: 'article' },
  { path: 'support', view: 'support', title: 'support.title' },
  { path: 'insights', view: 'insights', title: 'insights.title' },
  { path: 'about', view: 'about', title: 'about.title' },
];

function body(r, locale) {
  const L = JSON.stringify(locale);
  if (r.kind === 'platform') {
    return `import PlatformDetail from '@/views/platform-detail';
import { platforms, platformById } from '@/lib/content';

export const dynamicParams = false;
export function generateStaticParams() { return platforms.map((p) => ({ id: p.id })); }
export async function generateMetadata({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  return { title: platformById[id].name };
}
export default async function Page({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  return <PlatformDetail id={id} />;
}
`;
  }
  if (r.kind === 'tracker') {
    return `import { TrackerDetail } from '@/views/tracker';
import { platforms, platformById } from '@/lib/content';
import { translate } from '@/lib/i18n';

export const dynamicParams = false;
export function generateStaticParams() { return platforms.map((p) => ({ id: p.id })); }
export async function generateMetadata({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  return { title: \`\${platformById[id].name}: \${translate(${L}, 'nav.tracker')}\` };
}
export default async function Page({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  return <TrackerDetail id={id} />;
}
`;
  }
  if (r.kind === 'learn') {
    return `import LearnIndex from '@/views/learn';
import { listArticles } from '@/lib/learn';
import { translate } from '@/lib/i18n';

export const metadata = { title: translate(${L}, 'learn.title') };
export default function Page() {
  const articles = listArticles(${L}).map((a) => ({ slug: a.slug, title: a.title, summary: a.summary, order: a.order, minutes: Math.max(1, Math.round(a.words / 180)) }));
  return <LearnIndex articles={articles} />;
}
`;
  }
  if (r.kind === 'article') {
    return `import { LearnArticle } from '@/views/learn';
import { articleSlugs, getArticle, listArticles } from '@/lib/learn';

export const dynamicParams = false;
export function generateStaticParams() { return articleSlugs().map((slug) => ({ slug })); }
export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const a = getArticle(${L}, slug);
  return { title: a.title, description: a.summary[0] };
}
export default async function Page({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const a = getArticle(${L}, slug);
  const all = listArticles(${L});
  const next = all[all.findIndex((x) => x.slug === slug) + 1];
  return <LearnArticle a={{ title: a.title, summary: a.summary, html: a.html, minutes: Math.max(1, Math.round(a.words / 180)) }} next={next ? { slug: next.slug, title: next.title } : undefined} />;
}
`;
  }
  const imp = r.named ? `import { ${r.named} as View } from '@/views/${r.view}';` : `import View from '@/views/${r.view}';`;
  const meta = r.title ? `import { translate } from '@/lib/i18n';\n\nexport const metadata = { title: translate(${L}, '${r.title}') };\n` : `\n`;
  return `${imp}\n${meta}export default function Page() {\n  return <View />;\n}\n`;
}

for (const locale of ['en', 'hi']) {
  const base = locale === 'en' ? 'app/(en)' : 'app/hi';
  for (const r of routes) {
    const dir = path.join(base, r.path);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'page.tsx'), `// Generated by scripts/gen-routes.mjs\n${body(r, locale)}`);
  }
}
console.log('routes written');
